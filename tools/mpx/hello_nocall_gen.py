#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate a wasm module WITHOUT any native call: pure factorial loop,
exports _start. Isolates the interpreter from the invokeNative path."""
import os


def uleb(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def section(sid, payload):
    return bytes([sid]) + uleb(len(payload)) + payload


def vec(items):
    return uleb(len(items)) + b"".join(items)


name = lambda s: uleb(len(s)) + s.encode()

# type: (i32)->() for host echo, ()->() for main — keep same shapes as hello
types = vec([b"\x60" + vec([]) + vec([])])  # ()->()
type_sec = section(1, types)

func_sec = section(3, vec([uleb(0)]))  # main: type 0

export_sec = section(7, vec([name("_start") + b"\x00" + uleb(0)]))

body = bytearray()
body += b"\x01\x02\x7f"          # 2 x i32 locals ($i, $acc)
body += b"\x41\x01\x21\x01"      # acc = 1
body += b"\x41\x01\x21\x00"      # i = 1
body += b"\x02\x40"              # block $done
body += b"\x03\x40"              #   loop $top
body += b"\x20\x00"              #     local.get $i
body += b"\x41\x06"              #     i32.const 6
body += b"\x4e"                  #     i32.ge_s
body += b"\x0d\x01"              #     br_if $done (depth 1: loop is 0)
body += b"\x20\x01\x20\x00\x6c\x21\x01"  # acc *= i
body += b"\x20\x00\x41\x01\x6a\x21\x00"  # i += 1
body += b"\x0c\x00"              #     br $top
body += b"\x0b\x0b"              #   end / end
body += b"\x0b"                  # end (func)

code_sec = section(10, vec([uleb(len(body)) + bytes(body)]))

wasm = b"\x00asm\x01\x00\x00\x00" + type_sec + func_sec + export_sec + code_sec
print("wasm size:", len(wasm))

lines = [
    "/* Auto-generated by tools/mpx/hello_nocall_gen.py - do not edit.",
    " * Pure-compute wasm: factorial loop, NO imports, exports _start(). */",
    "#ifndef _MPX_HELLO_NOCALL_H_",
    "#define _MPX_HELLO_NOCALL_H_",
    "",
    "static const unsigned char k_hello_nocall[] __attribute__((aligned(4))) = {",
]
hexvals = ["0x%02x" % b for b in wasm]
for i in range(0, len(hexvals), 12):
    lines.append("    " + ", ".join(hexvals[i:i + 12]) + ",")
lines += [
    "};",
    "#define HELLO_NOCALL_SIZE (sizeof(k_hello_nocall))",
    "",
    "#endif /* _MPX_HELLO_NOCALL_H_ */",
]
out = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..",
                                    "app", "mpx", "hello_nocall.h"))
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out)
