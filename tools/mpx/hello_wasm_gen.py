#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate app/mpx/hello_wasm.h: a hand-assembled wasm module used as the
M1 smoke test for the WAMR interpreter bring-up on WL82.

Module contract:
  (import "env" "jl_log" (func $jl_log (param i32)))
  (func $main
    ;; factorial 5 via loop, then jl_log(120)
    ...)
  (export "_start" $main)

Run from repo root:  python tools/mpx/hello_wasm_gen.py
"""
import struct
import sys
import os


def uleb(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def section(sid, payload):
    return bytes([sid]) + uleb(len(payload)) + payload


def vec(items):
    return uleb(len(items)) + b"".join(items)


name = lambda s: uleb(len(s)) + s.encode()

# ---- type section: t0 = (i32)->(), t1 = ()->() ----
types = vec([b"\x60" + vec([b"\x7f"]) + vec([]),   # (i32) -> ()
             b"\x60" + vec([]) + vec([])])          # () -> ()
type_sec = section(1, types)

# ---- import: env.jl_log : t0 ----
imports = vec([name("env") + name("jl_log") + b"\x00" + uleb(0)])
import_sec = section(2, imports)

# ---- function: main : t1 ----
func_sec = section(3, vec([uleb(1)]))

# ---- export: "_start" -> func index 1 (0 = imported jl_log) ----
export_sec = section(7, vec([name("_start") + b"\x00" + uleb(1)]))

# ---- code: main body ----
body = bytearray()
body += b"\x01\x02\x7f"          # 1 group: 2 x i32 locals ($i, $acc)
body += b"\x41\x01\x21\x01"      # acc = 1
body += b"\x41\x01\x21\x00"      # i = 1
body += b"\x02\x40"              # block $done
body += b"\x03\x40"              #   loop $top
body += b"\x20\x00"              #     local.get $i
body += b"\x41\x06"              #     i32.const 6
body += b"\x4e"                  #     i32.ge_s
body += b"\x0d\x00"              #     br_if $done
body += b"\x20\x01\x20\x00\x6c\x21\x01"  # acc *= i
body += b"\x20\x00\x41\x01\x6a\x21\x00"  # i += 1
body += b"\x0c\x00"              #     br $top
body += b"\x0b\x0b"              #   end / end
body += b"\x20\x01"              # local.get $acc
body += b"\x10\x00"              # call $jl_log  (expect 120)
body += b"\x0b"                  # end (func)

code_sec = section(10, vec([uleb(len(body)) + bytes(body)]))

wasm = b"\x00asm\x01\x00\x00\x00" + type_sec + import_sec + func_sec \
    + export_sec + code_sec

assert wasm[:4] == b"\x00asm"
print("wasm size:", len(wasm))

lines = []
lines.append("/* Auto-generated by tools/mpx/hello_wasm_gen.py - do not edit.")
lines.append(" * Minimal wasm smoke module: imports env.jl_log(i32), computes")
lines.append(" * 5! in a loop and calls jl_log(120) from exported _start(). */")
lines.append("#ifndef _MPX_HELLO_WASM_H_")
lines.append("#define _MPX_HELLO_WASM_H_")
lines.append("")
lines.append("static const unsigned char k_hello_wasm[] = {")
hexvals = ["0x%02x" % b for b in wasm]
for i in range(0, len(hexvals), 12):
    lines.append("    " + ", ".join(hexvals[i:i + 12]) + ",")
lines.append("};")
lines.append("#define HELLO_WASM_SIZE (sizeof(k_hello_wasm))")
lines.append("")
lines.append("#endif /* _MPX_HELLO_WASM_H_ */")

out = os.path.join(os.path.dirname(__file__), "..", "..", "app", "mpx",
                   "hello_wasm.h")
out = os.path.normpath(out)
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out)

if len(sys.argv) > 1 and sys.argv[1] == "--emit-bin":
    with open(sys.argv[2], "wb") as f:
        f.write(wasm)
    print("wrote", sys.argv[2])
